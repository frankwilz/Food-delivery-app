from fastapi import APIRouter, Depends, HTTPException, Query, status

from app.core.config import RESTAURANTS_FILE
from app.repositories.restaurant_repository import RestaurantRepository
from app.schemas.error import ErrorResponse
from app.schemas.restaurant import Restaurant, RestaurantCreate, RestaurantUpdate
from app.services.restaurant_service import (
    DuplicateRestaurantError,
    EmptyUpdateError,
    RestaurantNotFoundError,
    RestaurantService,
)

router = APIRouter()

NOT_FOUND = {404: {"model": ErrorResponse, "description": "Restaurant not found"}}
DUPLICATE = {409: {"model": ErrorResponse, "description": "A restaurant with this name already exists at this address"}}
EMPTY_UPDATE = {400: {"model": ErrorResponse, "description": "The update body contained no fields"}}


def get_restaurant_service() -> RestaurantService:
    repository = RestaurantRepository(RESTAURANTS_FILE)
    return RestaurantService(repository)


@router.get(
    "/restaurants",
    response_model=list[Restaurant],
    summary="List, search or filter restaurants",
    description=(
        "Returns all restaurants. Optional query parameters narrow the list and can be combined: "
        "`search` (name or cuisine contains the text, case-insensitive), `cuisine` (exact cuisine, "
        "case-insensitive), `is_open` and `min_rating`. Returns an empty list if nothing matches."
    ),
)
def list_restaurants(
    search: str | None = Query(default=None, max_length=100, description="Text to look for in the name or cuisine."),
    cuisine: str | None = Query(default=None, max_length=50, description="Only restaurants with this cuisine."),
    is_open: bool | None = Query(default=None, description="Only open (true) or closed (false) restaurants."),
    min_rating: float | None = Query(default=None, ge=0, le=5, description="Only restaurants rated at least this."),
    service: RestaurantService = Depends(get_restaurant_service),
):
    return service.list_restaurants(search=search, cuisine=cuisine, is_open=is_open, min_rating=min_rating)


@router.get(
    "/restaurants/{restaurant_id}",
    response_model=Restaurant,
    summary="Get a restaurant",
    description="Returns the details of a single restaurant.",
    responses=NOT_FOUND,
)
def get_restaurant(restaurant_id: int, service: RestaurantService = Depends(get_restaurant_service)):
    try:
        return service.get_restaurant(restaurant_id)
    except RestaurantNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc


@router.post(
    "/restaurants",
    response_model=Restaurant,
    status_code=status.HTTP_201_CREATED,
    summary="Create a restaurant",
    description=(
        "Creates a restaurant. The id is generated by the server (highest existing id + 1) and may not be "
        "sent. `rating` defaults to 0 and `is_open` to true. A restaurant with the same name and address "
        "(case-insensitive) cannot be created twice."
    ),
    responses=DUPLICATE,
)
def create_restaurant(restaurant: RestaurantCreate, service: RestaurantService = Depends(get_restaurant_service)):
    try:
        return service.create_restaurant(restaurant)
    except DuplicateRestaurantError as exc:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(exc)) from exc


@router.patch(
    "/restaurants/{restaurant_id}",
    response_model=Restaurant,
    summary="Update a restaurant",
    description=(
        "Partially updates a restaurant: only the fields provided are changed and the id cannot be changed. "
        "At least one field must be sent, and the result must not duplicate another restaurant's name and address."
    ),
    responses={**EMPTY_UPDATE, **NOT_FOUND, **DUPLICATE},
)
def update_restaurant(
    restaurant_id: int,
    changes: RestaurantUpdate,
    service: RestaurantService = Depends(get_restaurant_service),
):
    try:
        return service.update_restaurant(restaurant_id, changes)
    except EmptyUpdateError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(exc)) from exc
    except RestaurantNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc
    except DuplicateRestaurantError as exc:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=str(exc)) from exc
