from fastapi import APIRouter, Depends, status

from app.core.config import CUSTOMERS_FILE
from app.repositories.customer_repository import CustomerRepository
from app.schemas.customer import Customer, CustomerCreate
from app.schemas.error import ErrorResponse
from app.services.customer_service import CustomerService

router = APIRouter()

DUPLICATE_EMAIL = {409: {"model": ErrorResponse, "description": "An account with this email already exists"}}


def get_customer_service() -> CustomerService:
    return CustomerService(CustomerRepository(CUSTOMERS_FILE))


@router.post(
    "/customers",
    response_model=Customer,
    status_code=status.HTTP_201_CREATED,
    summary="Register a customer",
    description=(
        "Creates a customer account. The id is generated by the server, the role is always `customer` "
        "and the account starts active, so none of these may be sent. Emails must be unique "
        "(case-insensitive). The password is stored only as a salted hash and is never returned."
    ),
    responses=DUPLICATE_EMAIL,
)
def register_customer(customer: CustomerCreate, service: CustomerService = Depends(get_customer_service)):
    return service.register(customer)
