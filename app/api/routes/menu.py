from typing import Annotated

from fastapi import APIRouter, Depends, Path, Query, status

from app.api.dependencies import MANAGER_ONLY, get_menu_service, require_manager
from app.schemas.error import ErrorResponse
from app.schemas.menu_item import MenuItem, MenuItemCreate, MenuItemUpdate
from app.services.menu_service import MenuService

router = APIRouter()

RESTAURANT_NOT_FOUND = {404: {"model": ErrorResponse, "description": "Restaurant not found"}}
ITEM_NOT_FOUND = {
    404: {"model": ErrorResponse, "description": "Restaurant not found, or the menu item does not belong to it"}
}
DUPLICATE_NAME = {409: {"model": ErrorResponse, "description": "The restaurant already has an item with this name"}}
EMPTY_UPDATE = {400: {"model": ErrorResponse, "description": "The update body contained no fields"}}


@router.get(
    "/restaurants/{restaurant_id}/menu",
    response_model=list[MenuItem],
    summary="List a restaurant's menu",
    description=(
        "Returns the menu items that belong to the given restaurant. Items that are temporarily "
        "unavailable are included with `is_available: false`. Items that were removed from the menu "
        "(deactivated) are hidden unless `include_inactive=true` is sent."
    ),
    responses=RESTAURANT_NOT_FOUND,
)
def list_menu_items(
    restaurant_id: Annotated[int, Path(description="The stable identifier of the restaurant whose menu is requested.")],
    include_inactive: bool = Query(default=False, description="Also return deactivated items."),
    service: MenuService = Depends(get_menu_service),
):
    return service.list_menu_items(restaurant_id, include_inactive)


@router.get(
    "/restaurants/{restaurant_id}/menu/{item_id}",
    response_model=MenuItem,
    summary="Get a menu item",
    description=(
        "Returns a single menu item belonging to the given restaurant. A deactivated item is still "
        "returned, marked with `is_active: false`."
    ),
    responses=ITEM_NOT_FOUND,
)
def get_menu_item(
    restaurant_id: Annotated[int, Path(description="The stable identifier of the restaurant that owns the menu item.")],
    item_id: Annotated[int, Path(description="The stable identifier of a menu item belonging to this restaurant.")],
    service: MenuService = Depends(get_menu_service),
):
    return service.get_menu_item(restaurant_id, item_id)


@router.post(
    "/restaurants/{restaurant_id}/menu",
    response_model=MenuItem,
    status_code=status.HTTP_201_CREATED,
    summary="Add a menu item",
    description=(
        "Creates a menu item for the given restaurant. The item ID is generated by the server "
        "and the restaurant is taken from the URL, so neither may be sent in the request body. "
        "Item names must be unique within a restaurant (case-insensitive). **Managers only.**"
    ),
    responses={**MANAGER_ONLY, **RESTAURANT_NOT_FOUND, **DUPLICATE_NAME},
    dependencies=[Depends(require_manager)],
)
def create_menu_item(
    restaurant_id: Annotated[int, Path(description="The stable identifier of the restaurant that will own the menu item.")],
    item: MenuItemCreate,
    service: MenuService = Depends(get_menu_service),
):
    return service.create_menu_item(restaurant_id, item)


@router.patch(
    "/restaurants/{restaurant_id}/menu/{item_id}",
    response_model=MenuItem,
    summary="Update a menu item",
    description=(
        "Partially updates a menu item belonging to the given restaurant. Only the fields "
        "provided are changed; the item ID and restaurant cannot be changed. At least one field "
        "must be sent, and a new name must not clash with another item at the same restaurant. "
        "Send `is_available: false` to mark an item as out of stock, or `is_active: true` to put a "
        "deactivated item back on the menu. **Managers only.**"
    ),
    responses={**EMPTY_UPDATE, **MANAGER_ONLY, **ITEM_NOT_FOUND, **DUPLICATE_NAME},
    dependencies=[Depends(require_manager)],
)
def update_menu_item(
    restaurant_id: Annotated[int, Path(description="The stable identifier of the restaurant that owns the menu item.")],
    item_id: Annotated[int, Path(description="The stable identifier of a menu item belonging to this restaurant.")],
    changes: MenuItemUpdate,
    service: MenuService = Depends(get_menu_service),
):
    return service.update_menu_item(restaurant_id, item_id, changes)


@router.delete(
    "/restaurants/{restaurant_id}/menu/{item_id}",
    response_model=MenuItem,
    summary="Deactivate a menu item",
    description=(
        "Removes a menu item from the restaurant's menu by setting `is_active` to `false` (a soft "
        "delete). The record is kept, so its id stays stable, and the updated item is returned. "
        "Deactivating an item that is already deactivated succeeds and changes nothing. **Managers only.**"
    ),
    responses={**MANAGER_ONLY, **ITEM_NOT_FOUND},
    dependencies=[Depends(require_manager)],
)
def deactivate_menu_item(
    restaurant_id: Annotated[int, Path(description="The stable identifier of the restaurant that owns the menu item.")],
    item_id: Annotated[int, Path(description="The stable identifier of a menu item belonging to this restaurant.")],
    service: MenuService = Depends(get_menu_service),
):
    return service.deactivate_menu_item(restaurant_id, item_id)
