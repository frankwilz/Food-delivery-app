from fastapi import APIRouter, Depends, HTTPException, status

from app.core.config import MENU_ITEMS_FILE, RESTAURANTS_FILE
from app.repositories.menu_item_repository import MenuItemRepository
from app.repositories.restaurant_repository import RestaurantRepository
from app.schemas.menu_item import MenuItem, MenuItemCreate, MenuItemUpdate
from app.services.menu_service import MenuService, NotFoundError

router = APIRouter()

RESTAURANT_NOT_FOUND = {404: {"description": "Restaurant not found"}}
ITEM_NOT_FOUND = {404: {"description": "Restaurant not found, or the menu item does not belong to it"}}


def get_menu_service() -> MenuService:
    return MenuService(
        MenuItemRepository(MENU_ITEMS_FILE),
        RestaurantRepository(RESTAURANTS_FILE),
    )


@router.get(
    "/restaurants/{restaurant_id}/menu",
    response_model=list[MenuItem],
    summary="List a restaurant's menu",
    description="Returns every menu item that belongs to the given restaurant.",
    responses=RESTAURANT_NOT_FOUND,
)
def list_menu_items(restaurant_id: int, service: MenuService = Depends(get_menu_service)):
    try:
        return service.list_menu_items(restaurant_id)
    except NotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc


@router.get(
    "/restaurants/{restaurant_id}/menu/{item_id}",
    response_model=MenuItem,
    summary="Get a menu item",
    description="Returns a single menu item belonging to the given restaurant.",
    responses=ITEM_NOT_FOUND,
)
def get_menu_item(restaurant_id: int, item_id: int, service: MenuService = Depends(get_menu_service)):
    try:
        return service.get_menu_item(restaurant_id, item_id)
    except NotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc


@router.post(
    "/restaurants/{restaurant_id}/menu",
    response_model=MenuItem,
    status_code=status.HTTP_201_CREATED,
    summary="Add a menu item",
    description=(
        "Creates a menu item for the given restaurant. The item ID is generated by the server "
        "and the restaurant is taken from the URL, so neither may be sent in the request body."
    ),
    responses=RESTAURANT_NOT_FOUND,
)
def create_menu_item(
    restaurant_id: int,
    item: MenuItemCreate,
    service: MenuService = Depends(get_menu_service),
):
    try:
        return service.create_menu_item(restaurant_id, item)
    except NotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc


@router.patch(
    "/restaurants/{restaurant_id}/menu/{item_id}",
    response_model=MenuItem,
    summary="Update a menu item",
    description=(
        "Partially updates a menu item belonging to the given restaurant. Only the fields "
        "provided are changed; the item ID and restaurant cannot be changed."
    ),
    responses=ITEM_NOT_FOUND,
)
def update_menu_item(
    restaurant_id: int,
    item_id: int,
    changes: MenuItemUpdate,
    service: MenuService = Depends(get_menu_service),
):
    try:
        return service.update_menu_item(restaurant_id, item_id, changes)
    except NotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc
